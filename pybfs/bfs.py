# -*- coding: utf-8 -*-
"""Baseflow Separation (BFS): the pybfs 0.2.0 ``bfs()`` interface.

Compatibility wrapper around `pybfs.core.model.simulate`. Signature and
output are unchanged; new code should call ``simulate`` directly.
"""

import warnings

from .core.model import simulate
from .data import streamflow_arrays
from .frames import base_table_from_frame, legacy_bfs_frame
from .legacy import bfs as _legacy
from .params import FlowMetrics, ModelParameters


def bfs(streamflow, SBT, basin_char, gw_hyd, flow, timestep='day', error_basis='total', use_jit=True):
    """Main BFS function for baseflow separation

    Performs physically-based baseflow separation using a coupled surface-subsurface
    reservoir model. Separates total streamflow into three components: surface flow,
    baseflow, and direct runoff. Uses an iterative approach to estimate precipitation
    impulses needed to match observed streamflow.

    Parameters
    ----------
    streamflow : pd.DataFrame
        DataFrame with columns 'Date' (datetime) and 'Streamflow' (m³/day,
        observed streamflow)
    SBT : pd.DataFrame
        Baseflow table with columns ['Xb','Z','S','Q']. Generated by
        base_table() function
    basin_char : list
        Basin characteristics [area, lb, x1, wb, por] (see `pybfs.params.ModelParameters`)
    gw_hyd : list
        Groundwater hydraulic parameters [alpha, beta, ks, kb, kz]
    flow : list
        Flow metrics [qthresh, rs, rb1, rb2, prec, fr4rise] (see `pybfs.params.FlowMetrics`)
    timestep : str, optional
        'day' (default) or 'hour'. Hourly runs use the pybfs 0.2.0 implementation
        unchanged (`pybfs.legacy`); hourly mode is untested.
    error_basis : str, optional
        Basis for the error columns ('base' or 'total'), default 'total'
    use_jit : bool, optional
        Ignored; kept for compatibility. There is a single implementation. In
        pybfs 0.2.0, False selected a pure-Python loop that skipped a possible
        impulse on the second time step (suspected issue M3, resolved toward the
        default/R behavior).

    Returns
    -------
    pd.DataFrame
        Columns Date, Qob, Qsim, SurfaceFlow, Baseflow, DirectRunoff, X, Eta, StSur,
        StBase, Impulse.L, Zs.L, Zb.L, Infil, Rech, RecessCount.T, AdjPctEr, Weight.
        Flows in m³/day, storages in m³, levels in m, impulse in m/day. See
        `pybfs.core.results.SimulationResult` for definitions.

    Warns
    -----
    UserWarning
        For negative parameters, Lb·Wb > area, or NaN in ``SBT`` (the run continues).

    Examples
    --------
    >>> streamflow_data = pd.read_csv('streamflow.csv')
    >>> params_df = pd.read_csv('site_parameters.csv')
    >>> basin_char, gw_hyd, flow = get_values_for_site(params_df, site_no)
    >>> SBT = base_table(lb, x1, wb, beta, kb, streamflow_data, por)
    >>> results = bfs(streamflow_data, SBT, basin_char, gw_hyd, flow)
    """
    if not use_jit:
        warnings.warn("use_jit is ignored: bfs() has a single implementation", DeprecationWarning, stacklevel=2)
    if timestep != 'day':
        return _legacy.bfs(streamflow, SBT, basin_char, gw_hyd, flow, timestep=timestep,
                           error_basis=error_basis, use_jit=use_jit)
    dates, q_obs = streamflow_arrays(streamflow)
    metrics = FlowMetrics.from_legacy(flow)
    result = simulate(q_obs, ModelParameters.from_legacy(basin_char, gw_hyd), metrics,
                      base_table=base_table_from_frame(SBT))
    return legacy_bfs_frame(result, dates, metrics, error_basis)
